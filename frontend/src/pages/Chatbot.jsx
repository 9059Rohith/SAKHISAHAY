/* Simple keyword matching for typed questions (demo only). */
const KEYWORDS = [
  { key: "emergency", words: ["emergency", "danger", "help me", "attack", "112", "ತುರ್ತು", "ಅಪಾಯ"] },
  { key: "followed", words: ["follow", "stalk", "chasing", "ಹಿಂಬಾಲ"] },
  { key: "harassment", words: ["harass", "report", "complaint", "fir", "abuse", "ಕಿರುಕುಳ", "ದೂರು"] },
  { key: "travel", words: ["travel", "trip", "cab", "taxi", "alone", "journey", "ಪ್ರಯಾಣ", "ಒಂಟಿ"] },
];

function getReplyKey(text) {
  const lower = text.toLowerCase();
  const match = KEYWORDS.find((entry) =>
    entry.words.some((word) => lower.includes(word))
  );
  return match ? match.key : "fallback";
}


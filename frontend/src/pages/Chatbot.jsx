function Chatbot() {
  const [language, setLanguage] = useState("en");
  const [messages, setMessages] = useState([]);
  const [inputValue, setInputValue] = useState("");
  const [error, setError] = useState("");
  const [isReplying, setIsReplying] = useState(false);

  const messagesRef = useRef(null);
  const replyTimerRef = useRef(null);
  const nextIdRef = useRef(1);

  const t = CONTENT[language];

  // Scroll the message list to the latest message.
  useEffect(() => {
    const el = messagesRef.current;
    if (el) {
      el.scrollTo({ top: el.scrollHeight, behavior: "smooth" });
    }
  }, [messages, isReplying, language]);

  // Clear any pending reply timer when the page unmounts.
  useEffect(() => {
    return () => clearTimeout(replyTimerRef.current);
  }, []);

  const createId = () => {
    const id = nextIdRef.current;
    nextIdRef.current += 1;
    return id;
  };

  const sendMessage = (rawText) => {
    const text = rawText.trim();

    if (!text) {
      setError(t.errorEmpty);
      return;
    }
    if (text.length > MAX_MESSAGE_LENGTH) {
      setError(t.errorTooLong);
      return;
    }
    if (isReplying) {
      return;
    }

    setError("");
    setInputValue("");
    setMessages((prev) => [
      ...prev,
      { id: createId(), role: "user", text },
    ]);
    setIsReplying(true);

    const replyKey = getReplyKey(text);
    replyTimerRef.current = setTimeout(() => {
      setMessages((prev) => [
        ...prev,
        { id: createId(), role: "bot", replyKey },
      ]);
      setIsReplying(false);
    }, REPLY_DELAY_MS);
  };

  const handleSubmit = (event) => {
    event.preventDefault();
    sendMessage(inputValue);
  };

  const handleKeyDown = (event) => {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      sendMessage(inputValue);
    }
  };

  const handleInputChange = (event) => {
    setInputValue(event.target.value);
    if (error) {
      setError("");
    }
  };

  const handleLanguageChange = (code) => {
    setLanguage(code);
    setError("");
  };

  return (
    <div className="chatbot-page" lang={language}>
      {/* Header */}
      <header className="chatbot-header">
        <div className="chatbot-header-inner">
          <span className="chatbot-brand">SAKHISAHAY</span>
          <Link to="/dashboard" className="chatbot-back-link">
            {t.backToDashboard}
          </Link>
        </div>
      </header>

      <main className="chatbot-main">
        {/* Introduction */}
        <section className="chatbot-intro">
          <span className="chatbot-demo-badge">{t.demoLabel}</span>
          <h1 className="chatbot-heading">{t.introHeading}</h1>
          <p className="chatbot-intro-text">{t.introText}</p>
        </section>

        {/* Notices */}
        <div className="chatbot-notices">
          <p className="chatbot-emergency" role="alert">
            <strong aria-hidden="true">🚨 </strong>
            {t.emergencyNotice}
          </p>
          <p className="chatbot-demo-notice">{t.demoNotice}</p>
        </div>

        {/* Language selection */}
        <div
          className="chatbot-language"
          role="group"
          aria-label={t.languageLabel}
        >
          <span className="chatbot-language-label">{t.languageLabel}:</span>
          <button
            type="button"
            className={`chatbot-lang-btn ${language === "en" ? "is-active" : ""}`}
            onClick={() => handleLanguageChange("en")}
            aria-pressed={language === "en"}
          >
            English
          </button>
          <button
            type="button"
            className={`chatbot-lang-btn ${language === "kn" ? "is-active" : ""}`}
            onClick={() => handleLanguageChange("kn")}
            aria-pressed={language === "kn"}
          >
            ಕನ್ನಡ
          </button>
        </div>

        {/* Chat interface */}
        <section className="chatbot-card" aria-label={t.chatTitle}>
          <div className="chatbot-card-header">
            <span className="chatbot-card-title">{t.chatTitle}</span>
            <span className="chatbot-card-tag">{t.demoLabel}</span>
          </div>

          <div
            className="chatbot-messages"
            ref={messagesRef}
            role="log"
            aria-live="polite"
          >
            {/* Welcome message (re-rendered in the selected language) */}
            <div className="chatbot-row chatbot-row-bot">
              <div className="chatbot-bubble chatbot-bubble-bot">
                <span className="chatbot-sender">{t.botName}</span>
                <p className="chatbot-text">{t.welcome}</p>
              </div>
            </div>

            {messages.map((message) =>
              message.role === "user" ? (
                <div key={message.id} className="chatbot-row chatbot-row-user">
                  <div className="chatbot-bubble chatbot-bubble-user">
                    <span className="chatbot-sender">{t.youName}</span>
                    <p className="chatbot-text">{message.text}</p>
                  </div>
                </div>
              ) : (
                <div key={message.id} className="chatbot-row chatbot-row-bot">
                  <div className="chatbot-bubble chatbot-bubble-bot">
                    <span className="chatbot-sender">{t.botName}</span>
                    <p className="chatbot-text">
                      {DEMO_RESPONSES[language][message.replyKey]}
                    </p>
                  </div>
                </div>
              )
            )}

            {isReplying && (
              <div className="chatbot-row chatbot-row-bot">
                <div
                  className="chatbot-bubble chatbot-bubble-bot chatbot-typing"
                  aria-label={t.typing}
                >
                  <span className="chatbot-dot" />
                  <span className="chatbot-dot" />
                  <span className="chatbot-dot" />
                </div>
              </div>
            )}
          </div>

          {/* Suggested questions */}
          <div className="chatbot-suggestions">
            <p className="chatbot-suggestions-heading">{t.suggestedHeading}</p>
            <div className="chatbot-suggestions-list">
              {SUGGESTED_QUESTIONS[language].map((question) => (
                <button
                  key={question.key}
                  type="button"
                  className="chatbot-chip"
                  onClick={() => sendMessage(question.text)}
                  disabled={isReplying}
                >
                  {question.text}
                </button>
              ))}
            </div>
          </div>

          {/* Input */}
          <form className="chatbot-form" onSubmit={handleSubmit} noValidate>
            <div className="chatbot-input-row">
              <input
                type="text"
                className="chatbot-input"
                value={inputValue}
                onChange={handleInputChange}
                onKeyDown={handleKeyDown}
                placeholder={t.inputPlaceholder}
                aria-label={t.inputLabel}
                aria-invalid={Boolean(error)}
                maxLength={MAX_MESSAGE_LENGTH + 50}
                autoComplete="off"
              />
              <button
                type="submit"
                className="chatbot-send-btn"
                disabled={isReplying}
              >
                {t.send}
              </button>
            </div>
            <div className="chatbot-form-footer">
              <span className="chatbot-error" role="alert">
                {error}
              </span>
              <span
                className={`chatbot-counter ${
                  inputValue.length > MAX_MESSAGE_LENGTH ? "is-over" : ""
                }`}
              >
                {inputValue.length}/{MAX_MESSAGE_LENGTH} {t.charCount}
              </span>
            </div>
          </form>
        </section>
      </main>
    </div>
  );
}

export default Chatbot;
